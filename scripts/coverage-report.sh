#!/usr/bin/env bash
# Runs both test suites with coverage and writes docs/coverage.md.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/docs/coverage.md"

cd "$root/backend"
go_packages="$(go test -race -cover ./... | awk '/coverage:/ {
  for (i = 1; i <= NF; i++) {
    if ($i ~ /^github\.com\//) pkg = $i
    if ($i == "coverage:") pct = $(i + 1)
  }
  sub(/^github\.com\/gutopin\/quotient\/backend\//, "", pkg)
  printf "| `%s` | %s |\n", pkg, pct
}')"
go test -coverprofile=coverage.out ./... >/dev/null
go_total="$(go tool cover -func=coverage.out | awk '/^total:/ { print $3 }')"

cd "$root/frontend"
pnpm --silent test:coverage >/dev/null
web_totals="$(node -e '
  const { total } = require("./coverage/coverage-summary.json")
  for (const key of ["statements", "branches", "functions", "lines"]) {
    console.log(`| ${key[0].toUpperCase() + key.slice(1)} | ${total[key].pct}% |`)
  }
')"

cat > "$out" <<MD
# Coverage report

Generated by \`make coverage-report\` on $(date -u +%Y-%m-%d). Interactive HTML
reports land in \`backend/coverage.html\` and \`frontend/coverage/index.html\`
after \`make coverage\`.

## Backend (Go)

Total: **$go_total** of statements.

| Package | Coverage |
| --- | --- |
$go_packages

\`cmd/api\` is tested through \`run\`: startup, graceful shutdown, invalid
config, a busy port and the healthcheck subcommand. Only the signal wiring in
\`main\` is left uncovered.

## Frontend (Vitest)

| Metric | Coverage |
| --- | --- |
$web_totals

Thresholds (90% statements, functions and lines; 85% branches) are enforced
in \`frontend/vite.config.ts\`, so the suite fails if coverage drops.
MD

echo "wrote ${out#"$root"/}"
